"""Preset questions for the demo, each with the input settings its task was trained on.

The wordings and criteria are copied from the training code (vjev/tasks.py, vjev/questions.py,
vjev/vggsound.py); tests/test_space.py fails if they drift.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Profile:
    """How a clip is decoded for one group of questions."""
    fps: float
    seconds: int
    max_side: int
    audio: bool
    matched: bool = False  # real-or-AI: first 12 frames, centre square, 256 px
    duration_in_state: bool = False


PROFILES = {
    "moment": Profile(fps=2.0, seconds=60, max_side=336, audio=True, duration_in_state=True),
    "query": Profile(fps=1.0, seconds=150, max_side=224, audio=True, duration_in_state=True),
    "sound": Profile(fps=2.0, seconds=10, max_side=336, audio=True),
    "ai": Profile(fps=8.0, seconds=6, max_side=448, audio=False, matched=True),
    "quality": Profile(fps=8.0, seconds=6, max_side=448, audio=False, duration_in_state=True),
}
MATCHED_FRAMES = 12
MATCHED_SIDE = 256

SOUND_CLASSES = {
    "people belly laughing": "adults laughing",
    "people giggling": "people giggling",
    "baby laughter": "a baby laughing",
    "people cheering": "people cheering",
    "people crowd": "crowd noise",
    "female speech, woman speaking": "a woman speaking",
    "male speech, man speaking": "a man speaking",
    "child speech, kid speaking": "a child speaking",
}

AI_QUESTION = {
    "type": "noul",
    "instructions": ("Was this video generated by an AI model, rather than filmed with a real "
                     "camera? Look at textures, motion, hands and faces, text, lighting and "
                     "physics."),
    "criteria": {"true": "AI-generated", "false": "real camera footage"},
}

QUALITY_QUESTIONS = {
    "visual_quality": (
        ("This is a short AI-generated or real video. How good is its visual quality: "
         "clarity, resolution, brightness and colour, and freedom from visual artifacts?"),
        ["bad: blurry, heavily distorted or hard to recognise",
         "average: clearly visible artifacts or low resolution",
         "good: clear, with only small flaws",
         "perfect: as clean as real camera footage"]),
    "temporal_consistency": (
        ("Do the subjects and background stay consistent from frame to frame, without "
         "flicker, morphing, or things changing shape or identity?"),
        ["bad: objects change shape or identity, or the video flickers heavily",
         "average: noticeable flicker, morphing or jumps",
         "good: mostly stable, with small glitches",
         "perfect: fully consistent, like real footage"]),
    "dynamic_degree": (
        "How much do the subjects and the camera move?",
        ["almost static: nearly nothing moves",
         "small motion: a little movement",
         "clear motion: subjects or camera move noticeably",
         "rich motion: large, natural movement, like real footage"]),
    "text_alignment": (
        "How well does the video match the text prompt it was generated from?",
        ["does not match the prompt",
         "matches only part of the prompt",
         "matches most of the prompt",
         "matches the whole prompt"]),
    "factual_consistency": (
        ("Is the video consistent with physics, anatomy and common sense? Look for impossible "
         "motion, malformed bodies or hands, and objects passing through each other."),
        ["bad: clear violations of physics, anatomy or common sense",
         "average: several implausible details",
         "good: small implausible details",
         "perfect: fully plausible, like real footage"]),
}

# Moment wordings. FunQA trained on the dataset's own instructions; these are the held-out
# wordings from vjev/wordings.py, on which the model showed no drop.
FUNNY = "At what point in the video does the funniest thing happen?"
MAGIC = "At what point does the magic trick happen in this video?"
QUERY = 'When does this happen in the video: "{query}"?'

CHOICES = ["Funniest moment", "Magic trick moment", "Find a described moment", "Laughing?",
           "Which sound?", "AI-generated?", "Video quality (5 scores)"]


def build(choices: list[str], query: str = "", prompt: str = "") -> dict[str, dict]:
    """Group the chosen presets by profile: {profile: {"state": {...}, "questions": {...}}}."""
    groups: dict[str, dict] = {}

    def add(profile: str, name: str, question: dict, state: dict | None = None):
        g = groups.setdefault(profile, {"state": dict(state or {}), "questions": {}})
        g["questions"][name] = question

    if "Funniest moment" in choices:
        add("moment", "funniest_moment", {"type": "moment", "instructions": FUNNY})
    if "Magic trick moment" in choices:
        add("moment", "magic_moment", {"type": "moment", "instructions": MAGIC})
    if "Find a described moment" in choices and query.strip():
        add("query", "described_moment",
            {"type": "moment", "instructions": QUERY.format(query=query.strip())})
    if "Laughing?" in choices:
        add("sound", "laughing", {"type": "noul",
                                  "instructions": "Can you hear someone laughing in this clip?",
                                  "criteria": {"true": "yes, someone laughs",
                                               "false": "no laughter"}})
    if "Which sound?" in choices:
        add("sound", "sound", {"type": "choice",
                               "instructions": "Which sound is most prominent in this clip?",
                               "criteria": dict(SOUND_CLASSES)})
    if "AI-generated?" in choices:
        add("ai", "ai_generated", dict(AI_QUESTION))
    if "Video quality (5 scores)" in choices:
        for k, (ins, crit) in QUALITY_QUESTIONS.items():
            if k == "text_alignment" and not prompt.strip():
                continue  # needs the generation prompt
            add("quality", k, {"type": "score", "instructions": ins, "criteria": list(crit)},
                {"prompt": prompt.strip()})
    return groups
